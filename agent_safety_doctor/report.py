def report_title(result: ScanResult) -> str:
    counts = result.counts
    if counts.get("critical") or counts.get("high"):
        return "Unsafe agent workspace detected."
    if counts.get("medium"):
        return "Agent safety gaps need review."
    return "No high-risk agent paths detected."


def executive_summary(score: int, counts: dict[str, int]) -> str:
    if counts.get("critical", 0):
        return "Critical agent execution risk was detected. Block autonomous execution until critical items are removed or explicitly gated."
    if counts.get("high", 0):
        return "High-risk agent execution conditions were detected. Do not allow autonomous agents near production-like tools until the high-severity items are fixed."
    if counts.get("medium", 0) or score < 85:
        return "Moderate agent-safety gaps were detected. This workspace needs explicit approval and rollback policies before serious autonomous use."
    return "No high-risk patterns were detected by the first-pass scanner. Keep approval gates and rollback documentation in place before expanding agent permissions."


def recommended_fixes(result: ScanResult) -> list[str]:
    categories = {finding.category for finding in result.findings}
    fixes: list[str] = []
    if {"secrets_exposure", "secret_value_pattern"} & categories:
        fixes.append("1. Move real credentials out of agent-accessible workspaces; keep only examples/placeholders in repo and rotate any exposed real values.")
    if "destructive_action" in categories:
        fixes.append("2. Require explicit approval before destructive commands; add dry-run defaults and backup verification before execution.")
    if any(category.startswith("mcp") for category in categories):
        fixes.append("3. Create a tool/MCP inventory with read/write/delete scope, credential source, and owner.")
    if {"dirty_workspace", "missing_version_control"} & categories:
        fixes.append("4. Require clean Git state before agent runs and diff review after agent runs.")
    if {"missing_policy", "missing_rollback"} & categories:
        fixes.append("5. Document approval, backup, rollback, and restore steps before letting agents interact with production data or infrastructure.")
    if not fixes:
        fixes.append("1. Keep the workspace low-permission and rerun this scan whenever agent tool access changes.")
    return fixes


def escape_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")
