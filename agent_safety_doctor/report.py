def render_markdown(result: ScanResult) -> str:
    score = result.score
    counts = result.counts
    lines = [
        "# Agent Safety Doctor Report",
        "",
        "## Scan metadata",
        "",
        f"- Workspace: `{result.metadata.root}`",
        f"- Started: `{result.metadata.started_at}`",
        f"- Completed: `{result.metadata.completed_at}`",
        f"- Files scanned: **{result.metadata.files_scanned}**",
        f"- Files skipped: **{result.metadata.files_skipped}**",
        f"- Bytes scanned: **{result.metadata.bytes_scanned}**",
    ]
    if result.metadata.config_path:
        lines.append(f"- Config: `{result.metadata.config_path}`")
    lines.extend(
        [
            "",
            "## Score",
            "",
            f"Safety score: **{score}/100**",
            f"Findings: **{counts['total']}** total — {counts['critical']} critical, {counts['high']} high, {counts['medium']} medium, {counts['low']} low, {counts['info']} info.",
            "",
            "## Executive summary",
            "",
            executive_summary(score, counts),
            "",
            "## Findings",
            "",
        ]
    )
    if not result.findings:
        lines.append("No obvious agent-safety risks found by the current scanner. This is not a full security review.")
    else:
        lines.extend(["| Severity | Category | Path | Line | Evidence | Detail | Fix |", "|---|---|---|---:|---|---|---|"])
        for finding in result.findings:
            lines.append(
                "| "
                + " | ".join(
                    [
                        finding.severity.upper(),
                        finding.category,
                        f"`{finding.path}`",
                        str(finding.line or ""),
                        escape_cell(finding.evidence or ""),
                        escape_cell(finding.detail),
                        escape_cell(finding.fix),
                    ]
                )
                + " |"
            )

    lines.extend(
        [
            "",
            "## Top recommended fixes",
            "",
            *recommended_fixes(result),
            "",
            "## Approval policy starter",
            "",
            "Actions requiring explicit human approval before execution:",
            "- deleting files, databases, buckets, volumes, or backups",
            "- force-pushing, hard-resetting, or cleaning Git state",
            "- touching production credentials, infrastructure, billing, or customer data",
            "- sending external messages, publishing, purchasing, or changing live environments",
            "- running scripts that contain destructive commands or unknown network side effects",
            "",
            "## Incident postmortem template",
            "",
            "- Incident title:",
            "- Date/time:",
            "- Agent/tool involved:",
            "- Intended task:",
            "- Actual behavior:",
            "- Tool calls/commands executed:",
            "- Files/services/data affected:",
            "- Root cause:",
            "- Missing guardrail:",
            "- Immediate fix:",
            "- Preventive control:",
            "- Owner/date:",
            "",
            "---",
            "Generated by `agent-safety-doctor`. This is a first-pass operational safety scan, not a full penetration test, compliance audit, or guarantee of agent safety.",
        ]
    )
    return "\n".join(lines) + "\n"


def render_json(result: ScanResult, pretty: bool = True) -> str:
    return json.dumps(result.as_dict(), indent=2 if pretty else None, sort_keys=True) + "\n"


def write_report(result: ScanResult, output: Path, fmt: str) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "json":
        output.write_text(render_json(result), encoding="utf-8")
    elif fmt == "html":
        output.write_text(render_html(result), encoding="utf-8")
    elif fmt == "markdown":
        output.write_text(render_markdown(result), encoding="utf-8")
    else:
        raise ValueError(f"Unsupported report format: {fmt}")


